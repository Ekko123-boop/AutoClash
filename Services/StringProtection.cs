        private static string Unmask(byte[] masked)
        {
            byte[] copy = new byte[masked.Length];
            for (int i = 0; i < masked.Length; i++)
            {
                copy[i] = (byte)(masked[i] ^ MaskKey[i % MaskKey.Length]);
            }
            return Encoding.UTF8.GetString(copy);
        }
